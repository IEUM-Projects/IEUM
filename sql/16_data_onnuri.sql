    SELECT m.id, t.merchant_count, t.digital_count, '2026-07-31' AS data_date
    FROM tmp_market_onnuri t JOIN markets m ON m.source_key = t.source_key
) AS new
ON DUPLICATE KEY UPDATE merchant_count = new.merchant_count, digital_count = new.digital_count, data_date = new.data_date;
DELETE FROM market_onnuri WHERE data_date < '2026-07-31';
DROP TEMPORARY TABLE IF EXISTS tmp_market_onnuri;

